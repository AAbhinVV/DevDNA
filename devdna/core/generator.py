"""
SDK Generator — turns accepted patterns into a real pip-installable Python package.

Uses Jinja2 with sandbox mode for security. Generates:
  - pyproject.toml
  - README.md with module docs
  - __init__.py with public exports
  - One .py module per suggested_module (with auto-detected imports)
"""

from __future__ import annotations

import re
import textwrap
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Optional

from jinja2.sandbox import SandboxedEnvironment
from jinja2 import DictLoader

from devdna.core.memory import StoredPattern


# =============================================================================
# JINJA2 TEMPLATES (rendered into generated SDK files)
# =============================================================================

